def _tab(w, header, rows, caption, raw_cols=(), extra="", **kw):
    """칸 글을 꾸밈 글(w.t)로 — raw_cols 의 칸은 HTML 그대로. extra = 표에 더할 클래스(apxdef = 결함 표 열 너비)"""
    out = [[c if i in raw_cols else w.t(str(c)) for i, c in enumerate(r)] for r in rows]
    return w.table(header=header, rows=out, caption=caption, cls="wr lf" + (" " + extra if extra else ""), html_cols=list(range(len(header))), small=True, **kw)


def _deftab(w, rows, start, caption, fn=None):
    """결함 표 — # · 무엇(굵게) + 처리(그 아래 줄) · 잘못된 예 · 정상 예. 처리 글이 넓은 칸을 쓰고, 예시 두 칸은 따로 둔다"""
    out = [[str(start + i + 1), f"{t}\n**처리** {p}", bad, good] for i, (t, bad, good, p) in enumerate(rows)]
    return _tab(w, ["#", "무엇 · 처리", "잘못된 예", "정상 예"], out, caption, raw_cols=(2, 3), extra="apxdef", fn=fn)


